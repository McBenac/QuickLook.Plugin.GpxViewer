# Fetches QuickLook.Common from the QuickLook release named in quicklook-version.txt into QuickLook.Common\,
# so the plugin builds against the same library QuickLook ships. Only that folder is downloaded (< 1 MB).
# Also writes GitVersion.cs, which QuickLook's own build generates and QuickLook.Common.csproj compiles in.
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$version = (Get-Content (Join-Path $root 'quicklook-version.txt') -Raw).Trim()
$target = Join-Path $root 'QuickLook.Common'
$stamp = Join-Path $target '.quicklook-version'

if ((Test-Path $stamp) -and ((Get-Content $stamp -Raw).Trim() -eq $version) -and (Test-Path (Join-Path $root 'GitVersion.cs'))) {
    "QuickLook.Common $version is already present"
    return
}

$source = Join-Path $root '.quicklook-src'
Remove-Item $source -Recurse -Force -ErrorAction SilentlyContinue
git -c advice.detachedHead=false clone --quiet --depth 1 --branch $version --filter=blob:none --sparse https://github.com/QL-Win/QuickLook.git $source
if ($LASTEXITCODE) { throw "Could not fetch QuickLook $version" }
git -C $source sparse-checkout set QuickLook.Common
if ($LASTEXITCODE) { throw 'Could not check out QuickLook.Common' }

Remove-Item $target -Recurse -Force -ErrorAction SilentlyContinue
Copy-Item (Join-Path $source 'QuickLook.Common') $target -Recurse
Remove-Item $source -Recurse -Force

@"
// Generated by scripts/get-quicklook-common.ps1, like QuickLook's own update-version.ps1.
using System.Reflection;

[assembly: AssemblyVersion("$version")]
[assembly: AssemblyInformationalVersion("$version")]
"@ | Set-Content (Join-Path $root 'GitVersion.cs') -Encoding UTF8

Set-Content $stamp $version
"QuickLook.Common $version fetched"
